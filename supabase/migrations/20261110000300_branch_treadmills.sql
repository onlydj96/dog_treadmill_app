-- =====================================================================
-- 지점별 트레드밀 기기 등록 (초기값)
-- 대수는 몰 규모·방문 패턴·운영시간을 고려해 정했다. 기기 점검·비활성은 status로 관리한다.
--  - 고양 스타필드점 12대: 가장 큰 교외형 몰, 주말 가족 방문이 많고 운영시간이 가장 길다(12시간)
--  - 영등포 타임스퀘어점 10대: 도심형 몰, 평일 저녁·주말 수요
--  - 용산 아이파크몰점 8대: 운영시간이 가장 짧고(10시간) 매장 구역이 아직 정해지지 않았다
-- 기기 이름: T-01, T-02, ... (지점 안에서 고유)
-- =====================================================================

insert into public.treadmills (branch_id, device_name)
select b.branch_id, 'T-' || lpad(n::text, 2, '0')
from (
  values
    ('b1000000-0000-4000-8000-000000000001'::uuid, 8),   -- 용산 아이파크몰점
    ('b1000000-0000-4000-8000-000000000002'::uuid, 12),  -- 고양 스타필드점
    ('b1000000-0000-4000-8000-000000000003'::uuid, 10)   -- 영등포 타임스퀘어점
) as b(branch_id, machines)
cross join lateral generate_series(1, b.machines) as n
on conflict (branch_id, device_name) do nothing;
